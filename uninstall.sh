#!/usr/bin/env bash
# ==============================================================================
# git-account-switcher Uninstaller for macOS and Linux
# ==============================================================================
set -e

GSWITCH_HOME="${GIT_ACCOUNT_SWITCHER_HOME:-$HOME}"
BIN_DIR="$GSWITCH_HOME/.local/bin"

echo ""
echo "Uninstalling git-account-switcher..."

rm -f "$BIN_DIR/git-account-switcher" "$BIN_DIR/gswitch" "$BIN_DIR/switch-git"
echo "[OK] Removed binaries from $BIN_DIR"

git config --global --unset alias.who 2>/dev/null || true
git config --global --unset alias.switch-acc 2>/dev/null || true
echo "[OK] Removed git aliases"

# Remove includeIf bindings generated by this tool.
removed_files=()
while IFS= read -r binding_key; do
    binding_key=$(printf '%s' "$binding_key" | tr -d '\r')
    [[ -n "$binding_key" ]] || continue
    binding_file=$(git config --global --get "$binding_key" 2>/dev/null || true)
    if [[ -n "$binding_file" && -f "$binding_file" ]] && grep -qE 'git-account-switcher.*cred' "$binding_file" 2>/dev/null; then
        git config --global --unset-all "$binding_key" 2>/dev/null || true
        removed_files+=("$binding_file")
    fi
done < <(git config --global --name-only --get-regexp '^includeif\.gitdir' 2>/dev/null || true)

remaining_bindings=$(git config --global --get-regexp '^includeif\.gitdir' 2>/dev/null || true)
for binding_file in "${removed_files[@]}"; do
    if [[ "$remaining_bindings" != *"$binding_file"* ]]; then
        rm -f "$binding_file"
        echo "[OK] Removed generated profile config: $binding_file"
    fi
done

# Remove any orphaned profile files generated by gswitch.
for binding_file in "$GSWITCH_HOME"/.gitconfig-*; do
    [[ -f "$binding_file" ]] || continue
    if grep -qE 'git-account-switcher.*cred' "$binding_file" 2>/dev/null; then
        rm -f "$binding_file"
        echo "[OK] Removed orphaned profile config: $binding_file"
    fi
done

# Remove shell completion loaders and generated completion files.
remove_loader() {
    local file="$1"
    [[ -f "$file" ]] || return 0
    local tmp="${file}.gswitch.tmp"
    grep -vE 'git-account-switcher shell completion|git-account-switcher.*completion\.(bash|zsh)' "$file" > "$tmp" 2>/dev/null || true
    mv "$tmp" "$file"
    echo "[OK] Removed completion loader from $file"
}
remove_loader "$GSWITCH_HOME/.bashrc"
remove_loader "$GSWITCH_HOME/.zshrc"
rm -f "$GSWITCH_HOME/.config/git-account-switcher/completion.bash" \
      "$GSWITCH_HOME/.config/git-account-switcher/completion.zsh" \
      "$GSWITCH_HOME/.config/git-account-switcher/completion.ps1"

if [[ "$1" == "--purge" ]]; then
    rm -rf "$GSWITCH_HOME/.config/git-account-switcher" "$GSWITCH_HOME/.config/switch-git"
    echo "[OK] Removed configuration directories"
fi

echo "Uninstallation completed."
echo ""
